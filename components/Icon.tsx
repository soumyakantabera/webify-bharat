const CUSTOM = INDIA_ICONS;

/** All Phosphor names available through <Icon name=… /> (used by the /brand grid). */
export const PHOSPHOR_NAMES = Object.keys(PH);

export type IconName = keyof typeof PH | `custom:${keyof typeof CUSTOM}`;

type Props = {
  name: string;
  size?: number;
  weight?: IconWeight;
  className?: string;
  /** Accessible label. Omit for decorative icons (rendered aria-hidden). */
  label?: string;
};

export function Icon({ name, size = 24, weight = "duotone", className, label }: Props) {
  const a11y = label ? { role: "img", "aria-label": label } : { "aria-hidden": true };
  if (name.startsWith("custom:")) {
    const C = CUSTOM[name.slice(7) as keyof typeof CUSTOM];
    return C ? <C size={size} className={`wb-ic${className ? ` ${className}` : ""}`} {...a11y} /> : null;
  }
  const P = PH[name as keyof typeof PH] as React.ComponentType<PhProps> | undefined;
  return P ? <P size={size} weight={weight} className={`wb-ic${className ? ` ${className}` : ""}`} {...a11y} /> : null;
}
